"""Generate formulas and complete parameter tables inside report figures.

The reported errors are conditional covariance or regression standard errors.
This script reuses the baseline models and scan masks; it adds no joint fit.
Run fit_chi_squared.py first after changing the primary analysis.
"""

import json

import matplotlib.pyplot as plt
import numpy as np
from scipy.optimize import curve_fit
from scipy.stats import linregress

import analyze as analysis
from paper_model_comparison import three_exponentials


OUTPUT = analysis.PROJECT_DIR / "latex" / "figure_fit_details"
ERROR_NOTE = (
    r"\par\smallskip\noindent Errors are conditional one-standard-error estimates; "
    r"model uncertainty is excluded."
)


def pair(value, error):
    """Round a value to the decimal place of a two-significant-digit error."""
    if not np.isfinite(error) or error <= 0:
        raise ValueError("A finite positive fit uncertainty is required")
    decimals = max(0, 1 - int(np.floor(np.log10(error))))
    return rf"${value:.{decimals}f}\pm{error:.{decimals}f}$"


def quality_cell(diagnostic):
    """Format a descriptive statistic and its nominal residual degrees of freedom."""
    return (rf"${diagnostic['reduced_chi_squared']:.3g}$ "
            rf"($\nu={diagnostic['degrees_of_freedom']}$)")


def write_details(name, formula, header, rows, note=""):
    """Write a non-floating table to be included within an existing figure."""
    columns = "l" + "r" * (len(header) - 1)
    lines = [
        "% Generated by analysis/figure_fit_details.py.",
        r"\par\smallskip\begingroup\small",
        r"\setlength{\tabcolsep}{5pt}",
        formula,
        rf"\par\smallskip\begin{{tabular}}{{{columns}}}\toprule",
        " & ".join(header) + r"\\\midrule",
    ]
    lines.extend(" & ".join(row) + r"\\" for row in rows)
    lines.extend([r"\bottomrule\end{tabular}", note, ERROR_NOTE, r"\par\endgroup"])
    (OUTPUT / f"{name}.tex").write_text("\n".join(lines) + "\n")


def plot_decay_residuals():
    """Plot residuals at their original panel size without a parameter table."""
    quality = json.loads((analysis.PROJECT_DIR / "analysis/fit_chi_squared.json").read_text())
    figure, axes = plt.subplots(5, 1, figsize=(9, 11))
    for axis, filename in zip(axes, analysis.TRACE_FILES):
        data = analysis.load_trace(filename)
        time, scans = data[:, 0], data[:, 1:]
        _, excluded = analysis.find_anomalous_scans(time, scans)
        mean = scans[:, ~excluded].mean(axis=1)
        parameters, keep = analysis.fit_trace(time, mean)
        prediction = analysis.biexponential_with_offset(time[keep], *parameters)
        label = filename.removeprefix("GaAs_RT_").removesuffix("_X.dat")
        axis.plot(time[keep], (mean[keep]-prediction)/np.ptp(mean[keep]), ".", markersize=2.2)
        axis.axhline(0, color="0.25", linewidth=.8)
        axis.set(xlabel="Delay (ps)", ylabel=f"{label}\n$resid./range$")
        diagnostic = quality["transients"][filename]
        axis.set_title(
            rf"$\chi^2_\nu={diagnostic['reduced_chi_squared']:.3g}$ "
            rf"($\nu={diagnostic['degrees_of_freedom']}$; diagonal diagnostic)",
            fontsize=10,
        )
        axis.grid(True, alpha=.25)
    figure.suptitle("Biexponential fit residuals (normalized by fitted-window range)")
    figure.tight_layout()
    figure.savefig(analysis.PLOT_DIR / "gaas_fit_residuals.png", dpi=180)
    plt.close(figure)


def main():
    OUTPUT.mkdir(exist_ok=True)
    result = {"uncertainties": "Conditional covariance or regression standard errors"}
    primary = json.loads((analysis.PROJECT_DIR / "analysis/results.json").read_text())
    quality = json.loads((analysis.PROJECT_DIR / "analysis/fit_chi_squared.json").read_text())
    sensitivity_lines = [
        "% Generated by analysis/figure_fit_details.py.",
        r"\begin{center}\small\begin{tabular}{lrr}\toprule",
        r"Additional fit & Diagonal $\chi^2_\nu$ & $\nu$\\\midrule",
    ]
    for item in quality["sensitivity_fits"]:
        sensitivity_lines.append(
            item["label"] + rf" & {item['reduced_chi_squared']:.3g} & {item['degrees_of_freedom']}\\"
        )
    sensitivity_lines.append(r"\bottomrule\end{tabular}\end{center}")
    (OUTPUT / "chi_sensitivity.tex").write_text("\n".join(sensitivity_lines)+"\n")
    spectrum = np.loadtxt(analysis.DATA_DIR / "spektrum.csv", delimiter=",")
    wavelength, signal = spectrum.T
    p, cov = curve_fit(
        analysis.gaussian_with_offset, wavelength, signal,
        p0=(signal.max()-np.median(signal), wavelength[np.argmax(signal)], 5, np.median(signal)),
        maxfev=20000,
    )
    errors = np.sqrt(np.diag(cov))
    spectral_rows = [
        [r"$A$ (a.u.)", pair(p[0], errors[0]), r"$B$ (a.u.)", pair(p[3], errors[3])],
        [r"$\lambda_0$ (nm)", pair(p[1], errors[1]), r"$\sigma_\lambda$ (nm)", pair(p[2], errors[2])],
    ]
    for label, gradient, value, other_label, other_gradient, other_value in [
        (r"Peak (a.u.)", [1, 0, 0, 1], p[0]+p[3],
         r"Half-max. (a.u.)", [.5, 0, 0, 1], p[0]/2+p[3]),
    ]:
        spectral_rows.append([
            label, pair(value, np.sqrt(np.array(gradient) @ cov @ gradient)),
            other_label, pair(other_value, np.sqrt(np.array(other_gradient) @ cov @ other_gradient)),
        ])
    spectral_rows.append([
        r"FWHM (nm)", pair(analysis.GAUSSIAN_FWHM*p[2], analysis.GAUSSIAN_FWHM*errors[2]),
        "", "",
    ])
    spectral_rows.append([r"$\chi^2_\nu$", "unavailable", "", ""])
    write_details(
        "spectrum", r"\(I(\lambda)=B+A\exp[-(\lambda-\lambda_0)^2/(2\sigma_\lambda^2)].\)",
        ["Quantity", "Estimate", "Quantity", "Estimate"], spectral_rows,
        r"\par\smallskip\noindent $\chi^2_\nu$ is unavailable without measurement-error estimates; "
        r"see Appendix~\ref{app:chi-squared}.",
    )
    result["spectrum"] = {"parameters": p.tolist(), "covariance": cov.tolist()}

    selected, _ = analysis.analyze_autocorrelation(p[1])
    names = [selected[group]["filename"] for group in ("vor", "nach")]
    iac_labels = [
        r"$B$ (recorded units)", r"$A_0$ (recorded units)",
        r"$C_1$ (recorded units)", r"$D_1$ (recorded units)",
        r"$C_2$ (recorded units)", r"$D_2$ (recorded units)",
        r"$x_0$ (ms)", r"$s$ (cycles)", r"$f$ (cycles/ms)",
        r"$b_2$ (cycles/ms$^2$)", r"$b_3$ (cycles/ms$^3$)",
    ]
    fits = [selected[group] for group in ("vor", "nach")]
    rows = [
        [label] + [pair(fit["parameters"][i], np.sqrt(fit["covariance"][i, i])) for fit in fits]
        for i, label in enumerate(iac_labels)
    ]
    rows.append([r"Pulse FWHM (fs)"] + [pair(fit["pulse_width_fs"], fit["pulse_stderr_fs"]) for fit in fits])
    rows.append([r"$\chi^2_\nu$", "unavailable", "unavailable"])
    formula = (
        r"\(\begin{aligned}S_{\rm fit}&=B+A_0g+h[C_1\cos(2\pi u)+D_1\sin(2\pi u)]\\"
        r"&\quad+g[C_2\cos(4\pi u)+D_2\sin(4\pi u)],\\"
        r"g&=e^{-u^2/(4s^2)},\quad h=e^{-3u^2/(16s^2)},\\"
        r"u&=f(x-x_0)+b_2(x-x_0)^2+b_3(x-x_0)^3.\end{aligned}\)"
    )
    for name in ("iac", "iac_residuals"):
        write_details(name, formula, ["Parameter"] + names, rows,
                      r"\par\smallskip\noindent Coefficients refer to the unnormalized recorded signal; "
                      r"the central wavelength is held fixed for the pulse-width errors. "
                      r"$\chi^2_\nu$ requires unavailable pointwise error estimates (Appendix~\ref{app:chi-squared}).")
    fringe_rows = [rows[i] for i in (6, 8, 9, 10)]
    write_details(
        "fringes", r"\(f_{\rm fit}(x)=du/dx=f+2b_2(x-x_0)+3b_3(x-x_0)^2.\)",
        ["Parameter"] + names, fringe_rows,
        r"\par\smallskip\noindent The red curves are derivatives of the raw-signal fits, "
        r"rather than independent fits to the blue points, so no separate $\chi^2_\nu$ is assigned. "
        r"The dashed lines are $f$.",
    )
    result["iac"] = {
        fit["filename"]: {"parameters": fit["parameters"].tolist(), "covariance": fit["covariance"].tolist()}
        for fit in fits
    }

    transient_fits, transient_rows = [], []
    for filename in analysis.TRACE_FILES:
        data = analysis.load_trace(filename)
        time, scans = data[:, 0], data[:, 1:]
        _, excluded = analysis.find_anomalous_scans(time, scans)
        mean = scans[:, ~excluded].mean(axis=1)
        parameters, mask, covariance = analysis.fit_trace(time, mean, return_covariance=True)
        # Transform the fitted lifetime gap into the displayed slow lifetime.
        transform = np.eye(5)
        transform[3, 1] = 1
        physical = transform @ parameters
        physical_covariance = transform @ covariance @ transform.T
        transient_fits.append((parameters, physical, physical_covariance))
        label = "PP" if "_PP_" in filename else "TG " + filename.split("_")[2]
        order = [1, 3, 0, 2, 4]
        factors = [1, 1, 1e6, 1e6, 1e6]
        transient_rows.append([label] + [
            pair(physical[i]*factor, np.sqrt(physical_covariance[i, i])*factor)
            for i, factor in zip(order, factors)
        ])
    transient_formula = r"\(S_{\rm fit}(t)=C+A_f e^{-t/\tau_f}+A_s e^{-t/\tau_s}.\)"
    transient_header = ["Trace", r"$\tau_f$ (ps)", r"$\tau_s$ (ps)", r"$A_f$", r"$A_s$", r"$C$"]
    quality_header = ["PP", "TG 5.6", "TG 6.5", "TG 8", "TG 12"]
    quality_table = (
        r"\par\smallskip Diagonal $\chi^2_\nu$ diagnostics:"
        r"\par\begin{tabular}{rrrrr}"
        + " & ".join(quality_header) + r"\\"
        + " & ".join(quality_cell(quality["transients"][name]) for name in analysis.TRACE_FILES)
        + r"\\\end{tabular}"
    )
    for name in ("decays", "decay_residuals"):
        write_details(name, transient_formula, transient_header, transient_rows,
                      quality_table + r"\par\smallskip\noindent $A_f,A_s,C$ are in $10^{-6}$ recorded signal units. "
                      r"These covariance standard errors differ from the 95\% repeat-scan intervals in Table~\ref{tab:tgfits}. "
                      r"$\chi^2_\nu$ uses repeat-mean errors; diagnostic uncertainties are unestimated "
                      r"(Appendix~\ref{app:chi-squared}).")
    result["transients"] = {
        filename: {"parameters_Af_tf_As_ts_C": physical.tolist(), "covariance": cov.tolist()}
        for filename, (_, physical, cov) in zip(analysis.TRACE_FILES, transient_fits)
    }

    q2 = np.array(primary["delay"]["q_squared"])
    rates = np.array(primary["delay"]["rates"])
    data8 = analysis.load_trace("GaAs_RT_8_X.dat")
    retained8 = np.ones(data8.shape[1]-1, dtype=bool)
    retained8[9] = False
    sensitivity_p, _ = analysis.fit_trace(data8[:, 0], data8[:, 1:][:, retained8].mean(axis=1))
    sensitivity_rates = rates.copy()
    sensitivity_rates[3] = 1 / (sensitivity_p[1]+sensitivity_p[3])
    regressions = [
        ("Finite-$q$ TG", linregress(q2[1:], rates[1:])),
        ("Including PP", linregress(q2, rates)),
        ("TG retaining scan 4", linregress(q2[1:], sensitivity_rates[1:])),
    ]
    rate_rows = [[name, pair(reg.slope*1e15, reg.stderr*1e15), pair(reg.intercept, reg.intercept_stderr)]
                 for name, reg in regressions]
    for row, key in zip(rate_rows, ("slow_tg", "slow_with_pp", "slow_keep_scan4")):
        row.append(quality_cell(quality["regressions"][key]))
    write_details(
        "diffusion", r"\(k(q)=b+Dq^2,\qquad k=1/\tau_s.\)",
        ["Regression", r"$D$ ($10^{-3}$ m$^2$/s)", r"$b$ (ps$^{-1}$)", r"$\chi^2_\nu$ ($\nu$)"], rate_rows,
        r"\par\smallskip\noindent Parameter errors are regression standard errors; plotted rate bars are "
        r"95\% repeat-scan bootstrap intervals. $\chi^2_\nu$ uses bootstrap rate standard deviations, "
        r"with unestimated diagnostic uncertainties (Appendix~\ref{app:chi-squared}).",
    )

    # Complete details for the PP two-/three-exponential residual comparison.
    pp = analysis.load_trace(analysis.TRACE_FILES[0])
    keep = pp[:, 0] >= analysis.FIT_START_PS
    pp_p, pp_cov = curve_fit(
        three_exponentials, pp[keep, 0], pp[keep, 1:].mean(axis=1)*1e6,
        p0=(180, .5, 40, 3, 10, 400, 30),
        bounds=((0, .05, 0, .05, 0, .05, -np.inf),
                (np.inf, 500, np.inf, 5000, np.inf, 1e5, np.inf)), maxfev=100000,
    )
    transform = np.eye(7)
    transform[3, 1] = 1
    transform[5, [1, 3]] = 1
    pp_physical = transform @ pp_p
    pp_physical_cov = transform @ pp_cov @ transform.T
    _, physical2, cov2 = transient_fits[0]
    model_rows = []
    for name, i2, i3, factor in [
        (r"$\tau_1$ (ps)", 1, 1, 1), (r"$\tau_2$ (ps)", 3, 3, 1),
        (r"$\tau_3$ (ps)", None, 5, 1), (r"$A_1$", 0, 0, 1e6),
        (r"$A_2$", 2, 2, 1e6), (r"$A_3$", None, 4, 1e6), (r"$C$", 4, 6, 1e6),
    ]:
        value2 = "--" if i2 is None else pair(physical2[i2]*factor, np.sqrt(cov2[i2, i2])*factor)
        # The triple fit already uses micro signal units.
        value3 = pair(pp_physical[i3], np.sqrt(pp_physical_cov[i3, i3]))
        model_rows.append([name, value2, value3])
    model_rows.append([
        r"$\chi^2_\nu$ (PP)", quality_cell(quality["transients"][analysis.TRACE_FILES[0]]),
        quality_cell(quality["pp_three"]),
    ])
    fast_rates = np.array([1 / fit[1][1] for fit in transient_fits])[1:]
    fast_reg = linregress(q2[1:], fast_rates)
    slow_reg = regressions[0][1]
    model_rows.extend([
        [r"$D_f,D_s$ ($10^{-3}$ m$^2$/s)", pair(fast_reg.slope*1e15, fast_reg.stderr*1e15), pair(slow_reg.slope*1e15, slow_reg.stderr*1e15)],
        [r"$b_f,b_s$ (ps$^{-1}$)", pair(fast_reg.intercept, fast_reg.intercept_stderr), pair(slow_reg.intercept, slow_reg.intercept_stderr)],
        [r"$\chi^2_\nu$ (rate lines)", quality_cell(quality["regressions"]["fast_tg"]),
         quality_cell(quality["regressions"]["slow_tg"])],
    ])
    write_details(
        "paper_diagnostics",
        r"\(S_m(t)=C+\sum_{j=1}^{m}A_j e^{-t/\tau_j},\quad m=2,3;\qquad k_{f,s}(q)=b_{f,s}+D_{f,s}q^2.\)",
        ["Parameter", "PP two-exp. / fast rate", "PP three-exp. / slow rate"], model_rows,
        r"\par\smallskip\noindent $A_j,C$: $10^{-6}$ recorded units. PP errors: covariance SE; "
        r"rate-line errors: regression SE. $\chi^2_\nu$ values are diagonal diagnostics "
        r"with unestimated uncertainties (Appendix~\ref{app:chi-squared}). "
        r"The last three rows describe the fast/slow rate lines.",
    )
    result["pp_three"] = {"parameters_A1_t1_A2_t2_A3_t3_C_micro_units": pp_physical.tolist(),
                          "covariance": pp_physical_cov.tolist()}
    (analysis.PROJECT_DIR / "analysis/figure_fit_details.json").write_text(json.dumps(result, indent=2)+"\n")
    plot_decay_residuals()
    print("Generated fit formulas and parameter tables for all fitted report figures.")


if __name__ == "__main__":
    main()
